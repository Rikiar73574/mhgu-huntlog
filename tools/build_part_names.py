#!/usr/bin/env python3
"""Build offline stagger labels from cached Kiranico text and owned RomFS tables.
Usage: build_part_names.py SOURCE_JSON ROMFS_ARC_DIR MTARC_TOOLS_DIR
Never infer a part from a single threshold; require the complete ordered table.
"""
import json,re,sys,struct
from pathlib import Path

def parse_page(text):
    title=re.search(r'^(.+?) - MHGU - Kiranico',text)
    url=re.search(r'https://mhgu.kiranico.com/monster/[a-zA-Z0-9]+',text)
    blocks=re.findall(r'Body Part\s+\| Stagger\s+\| Extract\n(.*?)(?=L\d+: #####|$)',text,re.S)
    rows=[]
    for block in blocks:
        found=[]
        for name,value,extract in re.findall(r'L\d+: (.+?)\s+\| (\d+)(?: \[\d+\])?\s+\| (.*)',block):
            color=re.search(r'\[([RGOW])\]',extract)
            found.append({'name':name.strip(),'base':int(value),'extract':color.group(1) if color else None})
        if len(found)>len(rows):rows=found
    return {'name':title.group(1) if title else None,'source':url.group(0) if url else None,'rows':rows}

def main():
    sys.path.insert(0,sys.argv[3]);from mtarc import Arc
    root=Path(__file__).resolve().parents[1]
    names=dict((int(i),name) for i,name in re.findall(r'(\d+)=>Some\("([^\"]+)"\)',(root/'combined/src/monsters.rs').read_text().split('// Names-only')[0]))
    aliases={'Niblesnarf':'Nibelsnarf','White Fatalis':'Old Fatalis','Yian Kut-ku':'Yian Kut-Ku'}
    pages=[parse_page(p['text']) if 'text' in p else p for p in json.loads(Path(sys.argv[1]).read_text())]
    byname={p['name']:p for p in pages}
    out={};issues=[];rust=['// Generated by tools/build_part_names.py. Labels: Kiranico; signatures: owned MHGU RomFS.','pub fn rows(species:u16)->&\'static [(&\'static str,u16)] {match species {']
    for species,name in names.items():
        page=byname.get(aliases.get(name,name));arc=Path(sys.argv[2])/f'em{species%256:03d}_{species//256:02d}.arc'
        reason=None
        if not page or not page['rows']:reason='missing Kiranico stagger table'
        elif species in (12,84,87):reason='non-generic actor layout'
        elif not arc.exists():reason='missing owned archive'
        else:
            a=Arc.open(arc);e=next((e for e in a.entries if e['name'].endswith('_dttune')),None)
            if e is None:reason='missing tune resource'
            else:
                b=a.read(e);thresholds=[struct.unpack_from('<H',b,0x3c+10*i)[0] for i in range(8)]
                rows=[dict(r) for r in page['rows']]
                indices=list(range(len(rows)))
                if [r['base'] for r in rows]!=thresholds[:len(rows)]:
                    # Some generic actors retain an unused interior slot. Zero
                    # extract plus the exact default record identifies that pad.
                    indices=[i for i in range(8) if b[0x3c+10*i:0x46+10*i]!=bytes.fromhex('640000000000ffff0000')]
                expected=[thresholds[i] for i in indices] if len(indices)<=8 else []
                if len(rows)>8 or [r['base'] for r in rows]!=expected:reason='ordered threshold mismatch'
                else:
                    for r,i in zip(rows,indices):r['slot']=i
                    out[str(species)]={**page,'rows':rows,'signature':thresholds}
                    slot_rows={r['slot']:r for r in rows}
                    rows=[slot_rows.get(i,{'name':'','base':0}) for i in range(max(indices)+1)]
                    rust.append(f'{species}=>&['+','.join('('+json.dumps(r['name'])+','+str(r['base'])+')' for r in rows)+'],')
        if reason:issues.append({'species':species,'name':name,'reason':reason,'source':page['source'] if page else None})
    rust+=['_=>&[],}}','pub fn signature(species:u16)->Option<[u16;8]>{match species{']
    rust += [f'{k}=>Some({v["signature"]}),'.replace(' ', '') for k,v in out.items()]
    rust += ['_=>None,}}']
    (root/'combined/src/part_names.rs').write_text('\n'.join(rust)+'\n')
    (root/'history/part-names.js').write_text('export const partNames='+json.dumps(out,separators=(',',':'))+';\n')
    (root/'history/part-names.json').write_text(json.dumps({'monsters':out,'unmapped':issues},indent=2)+'\n')
    print(f'Mapped {len(out)}/{len(names)} species');print(json.dumps(issues,indent=2))

if __name__=='__main__':main()
